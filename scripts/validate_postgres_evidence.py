"""Run paired contracts and optional profiling in disposable PostgreSQL schemas.

Requires WTB_EVIDENCE_POSTGRES_DSN; never stores that potentially secret DSN.
Only namespaces generated by this process are removed in the finally block.
"""

import argparse
import json
import os
import uuid
from contextlib import ExitStack
from pathlib import Path

import psycopg
from psycopg import sql

from compare_evidence_lifecycle import run as compare
from profile_evidence_lifecycle import run as profile
from tests.unit.evidence.test_publication_sink import setup_sink
from wtb.infrastructure.evidence.postgres_store import (
    PostgresEvidenceStore,
    PostgresPublicationSink,
)


def run(n):
    dsn = os.environ["WTB_EVIDENCE_POSTGRES_DSN"]
    namespaces = []
    resources = ExitStack()

    def factory():
        schema = "wtb_bench_" + uuid.uuid4().hex
        namespaces.append(schema)
        return setup_sink(
            store=resources.enter_context(PostgresEvidenceStore(dsn, schema=schema)),
            sink_type=PostgresPublicationSink,
        )

    try:
        with psycopg.connect(dsn) as connection:
            version = connection.execute("SELECT version()").fetchone()[0]
        result = {
            "postgres_version": version,
            "psycopg_version": psycopg.__version__,
            "connection_policy": "instance-owned pool; fresh transaction and schema-wide advisory lock per operation; eager schema bootstrap",
            "paired": compare(factory),
        }
        if n:
            result["profile"] = profile(n, factory)
        return result
    finally:
        resources.close()
        with psycopg.connect(dsn) as connection:
            for schema in namespaces:
                connection.execute(
                    sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                        sql.Identifier(schema)
                    )
                )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--n", type=int, default=0)
    args = parser.parse_args()
    if args.n < 0:
        parser.error("--n must be nonnegative")
    args.output.write_text(json.dumps(run(args.n), indent=2) + "\n", encoding="utf-8")
